/* Детерминированный генератор, чтобы цифры не прыгали между перезагрузками */
AS.rng = function (seed) {
  let s = 0;
  for (const ch of String(seed)) s = (s * 31 + ch.charCodeAt(0)) >>> 0;
  s = s || 1;
  return function () {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5; s >>>= 0;
    return s / 4294967296;
  };
};

/* Максимальная просадка кривой доходности, % от пика капитала */
AS.maxDD = function (arr) {
  let peak = -Infinity, worst = 0;
  for (const v of arr) { peak = Math.max(peak, v); worst = Math.max(worst, (peak - v) / (1 + peak / 100)); }
  return worst;
};

/* Кривая накопленной доходности: растёт с откатами, заканчивается ровно на roi, макс. просадка ≈ dd */
AS.curve = function (agentId, period, roi, dd, points) {
  const n = points || Math.max(24, Math.min(90, period * 2));
  const rand = AS.rng(agentId + ':' + period);
  const shocks = [];
  for (let i = 0; i < n; i++) shocks.push((rand() + rand() + rand()) / 1.5 - 1); // ~[-1;1], к центру
  const build = k => {
    const out = [0];
    let cum = 0;
    const inc = shocks.map(z => 1 + k * z);
    const total = inc.reduce((a, b) => a + b, 0);
    for (const v of inc) { cum += v; out.push(roi * cum / total); }
    return out;
  };
  const maxDD = AS.maxDD;
  let lo = 0, hi = 30;
  for (let it = 0; it < 40; it++) {
    const mid = (lo + hi) / 2;
    if (maxDD(build(mid)) > dd) hi = mid; else lo = mid;
  }
  return build(lo);
};

AS.fmt = {
  usd(v, digits) {
    const d = digits == null ? 2 : digits;
    const s = Math.abs(v).toLocaleString('ru-RU', { minimumFractionDigits: d, maximumFractionDigits: d }).replace(',', '.');
    return (v < 0 ? '−' : '') + '$' + s;
  },
  signUsd(v, digits) { return (v >= 0 ? '+' : '−') + AS.fmt.usd(Math.abs(v), digits); },
  pct(v, digits) { const d = digits == null ? 2 : digits; return (v >= 0 ? '+' : '−') + Math.abs(v).toFixed(d) + '%'; },
  int(v) { return Math.round(v).toLocaleString('ru-RU'); }
};

